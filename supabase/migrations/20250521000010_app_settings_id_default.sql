/* ══════════════════════════════════════════════════════
   NEXWAVE CORE ERP - Fix app_settings.id default
   The id column is BIGINT but was created without a default value,
   causing INSERT to fail with "null value in column id".
   ══════════════════════════════════════════════════════ */

DO $$
BEGIN
    ALTER TABLE app_settings ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
EXCEPTION
    WHEN duplicate_object THEN NULL;
    WHEN object_not_in_prerequisite_state THEN NULL;
END $$;
